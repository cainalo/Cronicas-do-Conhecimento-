import type { CharacterTimeAlignment } from '@/lib/narration-timeline';

export interface ElevenLabsAlignmentResult {
  alignment: CharacterTimeAlignment;
  /** Provider-reported overall alignment loss; lower generally indicates a better fit. */
  loss: number;
}

export interface ElevenLabsTtsWithTimestampsResult {
  audioBase64: string;
  alignment: CharacterTimeAlignment;
}

interface ElevenLabsAlignedCharacter {
  text: string;
  start: number;
  end: number;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function parseCharacter(value: unknown, index: number): ElevenLabsAlignedCharacter {
  if (!isRecord(value)) {
    throw new Error('ElevenLabs alignment character ' + index + ' is not an object.');
  }

  const { text, start, end } = value;
  if (typeof text !== 'string' || Array.from(text).length !== 1) {
    throw new Error('ElevenLabs alignment item ' + index + ' must contain exactly one Unicode code point.');
  }
  if (typeof start !== 'number' || typeof end !== 'number'
    || !Number.isFinite(start) || !Number.isFinite(end)
    || start < 0 || end < start) {
    throw new Error('ElevenLabs alignment timestamps are invalid at character ' + index + '.');
  }

  return { text, start, end };
}

function assertAlignmentMatchesText(
  alignment: CharacterTimeAlignment,
  expectedText: string,
  providerLabel: string,
): void {
  const expectedCharacters = Array.from(expectedText);
  const lengths = [
    alignment.characters.length,
    alignment.character_start_times_seconds.length,
    alignment.character_end_times_seconds.length,
  ];

  if (typeof expectedText !== 'string' || expectedText.length === 0) {
    throw new Error('The exact transcript submitted for ' + providerLabel + ' is required.');
  }
  if (lengths.some((length) => length !== expectedCharacters.length)) {
    throw new Error(
      providerLabel + ' character count mismatch: transcript has ' + expectedCharacters.length
      + ' Unicode code points; alignment arrays have ' + lengths.join('/ ') + '.',
    );
  }

  let previousStart = -1;
  let previousEnd = -1;
  alignment.characters.forEach((character, index) => {
    if (typeof character !== 'string' || Array.from(character).length !== 1) {
      throw new Error(providerLabel + ' character at position ' + index + ' is not one Unicode code point.');
    }
    if (character !== expectedCharacters[index]) {
      throw new Error(
        providerLabel + ' transcript mismatch at character ' + index + ': expected "'
        + expectedCharacters[index] + '", received "' + character + '".',
      );
    }

    const start = alignment.character_start_times_seconds[index];
    const end = alignment.character_end_times_seconds[index];
    if (!Number.isFinite(start) || !Number.isFinite(end) || start < 0 || end < start) {
      throw new Error(providerLabel + ' timestamps are invalid at character ' + index + '.');
    }
    if (start < previousStart || end < previousEnd) {
      throw new Error(providerLabel + ' timestamps are not monotonic at character ' + index + '.');
    }
    previousStart = start;
    previousEnd = end;
  });
}

function parseCharacterArrayAlignment(
  value: unknown,
  expectedText: string,
  providerLabel: string,
): CharacterTimeAlignment {
  if (!isRecord(value)) {
    throw new Error(providerLabel + ' alignment is not an object.');
  }
  if (!Array.isArray(value.characters)
    || !Array.isArray(value.character_start_times_seconds)
    || !Array.isArray(value.character_end_times_seconds)) {
    throw new Error(providerLabel + ' alignment is missing one or more character timing arrays.');
  }

  const alignment: CharacterTimeAlignment = {
    characters: value.characters as string[],
    character_start_times_seconds: value.character_start_times_seconds as number[],
    character_end_times_seconds: value.character_end_times_seconds as number[],
  };
  assertAlignmentMatchesText(alignment, expectedText, providerLabel);
  return alignment;
}

/**
 * Adapts the documented ElevenLabs POST /v1/forced-alignment response:
 * { characters: [{ text, start, end }], words: [...], loss }.
 *
 * Use this when aligning existing audio (for example, a Gemini-generated WAV).
 * For audio newly generated by ElevenLabs, prefer the TTS with-timestamps endpoint below,
 * which returns the audio and character alignment in one response.
 *
 * The provider's transcript must match the exact text submitted for alignment. This function
 * rejects omissions, Unicode normalization, and malformed timing instead of fabricating offsets.
 * Make the API request on a trusted server; never ship an ElevenLabs API key in the web bundle.
 */
export function parseElevenLabsForcedAlignmentResponse(
  payload: unknown,
  expectedText: string,
): ElevenLabsAlignmentResult {
  if (!isRecord(payload)) {
    throw new Error('ElevenLabs forced-alignment response is not an object.');
  }
  if (typeof expectedText !== 'string' || expectedText.length === 0) {
    throw new Error('The exact transcript submitted for alignment is required.');
  }
  if (!Array.isArray(payload.characters)) {
    throw new Error('ElevenLabs response does not contain a characters array.');
  }
  if (typeof payload.loss !== 'number' || !Number.isFinite(payload.loss) || payload.loss < 0) {
    throw new Error('ElevenLabs response contains an invalid alignment loss.');
  }

  const parsed = payload.characters.map(parseCharacter);
  const alignment: CharacterTimeAlignment = {
    characters: parsed.map((item) => item.text),
    character_start_times_seconds: parsed.map((item) => item.start),
    character_end_times_seconds: parsed.map((item) => item.end),
  };
  assertAlignmentMatchesText(alignment, expectedText, 'ElevenLabs forced alignment');

  return { alignment, loss: payload.loss };
}

/**
 * Adapts POST /v1/text-to-speech/{voice_id}/with-timestamps.
 * The alignment object already matches CharacterTimeAlignment; audio_base64 contains the
 * generated audio. Always use the original-text alignment, not normalized_alignment, unless
 * an explicit normalization-to-source offset map has been implemented.
 *
 * Prefer this endpoint when ElevenLabs is generating the speech: it avoids a second alignment
 * request. The API key must stay on a trusted server or secure editorial build pipeline.
 */
export function parseElevenLabsTtsWithTimestampsResponse(
  payload: unknown,
  expectedText: string,
): ElevenLabsTtsWithTimestampsResult {
  if (!isRecord(payload)) {
    throw new Error('ElevenLabs TTS-with-timestamps response is not an object.');
  }
  if (typeof payload.audio_base64 !== 'string' || payload.audio_base64.trim().length === 0) {
    throw new Error('ElevenLabs TTS-with-timestamps response has no audio_base64.');
  }

  const alignment = parseCharacterArrayAlignment(
    payload.alignment,
    expectedText,
    'ElevenLabs TTS-with-timestamps',
  );
  return { audioBase64: payload.audio_base64, alignment };
}
